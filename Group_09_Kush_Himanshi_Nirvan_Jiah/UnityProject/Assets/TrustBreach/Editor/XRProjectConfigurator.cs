using System.Text;
using UnityEditor;
using UnityEditor.Build;
using UnityEngine;
using UnityEngine.Rendering.Universal;

namespace TrustBreach.Editor
{
    /// <summary>
    /// Idempotent Quest (Android) + macOS Editor/Simulator project settings for TrustBreach.
    /// Only values that differ from the target are changed; everything else is reported unchanged.
    /// XR loader / OpenXR feature selection is already correct in this project (OpenXR + Meta XR feature +
    /// Oculus Touch profiles on both Standalone and Android) and is validated, not rewritten, here.
    /// </summary>
    public static class XRProjectConfigurator
    {
        public const string AndroidApplicationId = "com.nmims.trustbreach.group09";
        private const string TemplateApplicationId = "com.UnityTechnologies.com.unity.template.urpblank";

        private const string MobileRenderPipelinePath = "Assets/Settings/Mobile_RPAsset.asset";
        private const string PCRenderPipelinePath = "Assets/Settings/PC_RPAsset.asset";

        [MenuItem("TrustBreach/Phase 1/Apply XR Project Settings", priority = 10)]
        private static void ApplyFromMenu()
        {
            Debug.Log(Apply());
        }

        public static string Apply()
        {
            var log = new StringBuilder("TrustBreach XR project settings:\n");

            // Replace only Unity's template placeholder; never overwrite an identifier the team chose.
            string currentId = PlayerSettings.GetApplicationIdentifier(NamedBuildTarget.Android);
            if (currentId == TemplateApplicationId || string.IsNullOrEmpty(currentId))
            {
                PlayerSettings.SetApplicationIdentifier(NamedBuildTarget.Android, AndroidApplicationId);
                log.AppendLine($"  Android application id: {currentId} -> {AndroidApplicationId}");
            }
            else
            {
                log.AppendLine($"  Android application id unchanged: {currentId}");
            }

            // The Interaction SDK rig supports controllers and hands; declare both in the Quest manifest.
            OVRProjectConfig projectConfig = OVRProjectConfig.CachedProjectConfig;
            if (projectConfig.handTrackingSupport == OVRProjectConfig.HandTrackingSupport.ControllersOnly)
            {
                projectConfig.handTrackingSupport = OVRProjectConfig.HandTrackingSupport.ControllersAndHands;
                OVRProjectConfig.CommitProjectConfig(projectConfig);
                log.AppendLine("  Quest hand tracking support: ControllersOnly -> ControllersAndHands");
            }
            else
            {
                log.AppendLine($"  Quest hand tracking support unchanged: {projectConfig.handTrackingSupport}");
            }

            // Quest (Android default quality level "Mobile"): native eye-buffer resolution keeps text legible,
            // which matters for reading phishing artifacts; short shadow distance suits an indoor office.
            var mobile = AssetDatabase.LoadAssetAtPath<UniversalRenderPipelineAsset>(MobileRenderPipelinePath);
            if (mobile != null)
            {
                SetIfDifferent(log, mobile, "Mobile URP renderScale", mobile.renderScale, 1f, v => mobile.renderScale = v);
                SetIfDifferent(log, mobile, "Mobile URP shadowDistance", mobile.shadowDistance, 20f, v => mobile.shadowDistance = v);
            }

            // Editor / Meta XR Simulator (Standalone default quality level "PC"): MSAA 4x to match Quest output.
            var pc = AssetDatabase.LoadAssetAtPath<UniversalRenderPipelineAsset>(PCRenderPipelinePath);
            if (pc != null && pc.msaaSampleCount != 4)
            {
                log.AppendLine($"  PC URP MSAA: {pc.msaaSampleCount}x -> 4x");
                pc.msaaSampleCount = 4;
                EditorUtility.SetDirty(pc);
            }

            AssetDatabase.SaveAssets();

            // Regenerate Assets/Plugins/Android/AndroidManifest.xml with Meta's tool so it matches OVRProjectConfig.
            OVRManifestPreprocessor.GenerateOrUpdateAndroidManifest(silentMode: true);
            log.AppendLine("  Android manifest regenerated by OVRManifestPreprocessor");

            return log.ToString();
        }

        private static void SetIfDifferent(StringBuilder log, Object asset, string label, float current, float target,
            System.Action<float> setter)
        {
            if (Mathf.Approximately(current, target))
            {
                log.AppendLine($"  {label} unchanged: {current}");
                return;
            }
            setter(target);
            EditorUtility.SetDirty(asset);
            log.AppendLine($"  {label}: {current} -> {target}");
        }
    }
}
